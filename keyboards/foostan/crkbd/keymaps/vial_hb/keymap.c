/*
 * Split-link heartbeat (added on top of foostan's official Vial keymap).
 * The master pings the slave every 500 ms. If a slave that was already linked
 * stops hearing pings for 5 s (link lost or master stalled), it reboots itself
 * so the halves resync without unplugging USB. QMK's SPLIT_WATCHDOG only covers
 * the first handshake after boot, not a link lost later.
 */
#include "transactions.h"

/* Written by the slave's transport thread, read by its main loop: keep them volatile. */
static volatile uint32_t hb_last_rx = 0;
static volatile bool     hb_linked  = false;

static void hb_slave_handler(uint8_t in_len, const void *in, uint8_t out_len, void *out) {
    hb_last_rx = timer_read32();
    hb_linked  = true;
}

void keyboard_post_init_user(void) {
    transaction_register_rpc(USER_HEARTBEAT, hb_slave_handler);
}

void housekeeping_task_user(void) {
    if (is_keyboard_master()) {
        static uint32_t last_tx = 0;
        static uint8_t  seq     = 0;
        if (timer_elapsed32(last_tx) > 500) {
            last_tx = timer_read32();
            seq++;
            /* No-op while the halves are disconnected: QMK skips RPCs then. */
            transaction_rpc_send(USER_HEARTBEAT, sizeof(seq), &seq);
        }
    } else if (hb_linked) {
        uint32_t last = hb_last_rx; /* read before "now" so the difference can't go negative */
        uint32_t now  = timer_read32();
        if ((int32_t)(now - last) > 5000) {
            mcu_reset();
        }
    }
}
